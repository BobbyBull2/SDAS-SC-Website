import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const errors=[],checks=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
page.on('pageerror',error=>errors.push(error.message));
// Movement tests use local avatar bytes to isolate timing from remote media latency.
const avatar=await readFile('public/images/sdas-spaceman.png');
await page.route(/https:\/\/[^/]*robertsspaceindustries\.com\//,route=>route.fulfill({contentType:'image/png',body:avatar}));
await page.clock.install({time:new Date('2026-10-09T15:00:00Z')});
await page.clock.pauseAt(new Date('2026-10-09T15:00:01Z'));
await page.goto('http://localhost:5174/',{waitUntil:'networkidle'});
const rail=page.locator('.crew-rail');
await page.locator('#crew').scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('.crew-rail').dataset.running==='true');
const left=()=>rail.evaluate(e=>e.scrollLeft);
const width=await page.locator('[data-copy=original]').evaluate(e=>e.getBoundingClientRect().width);
assert.equal(await page.locator('[data-copy=original] .crew-card').count(),69);
assert.equal(await page.locator('.crew-group[aria-hidden=true]').count(),2);
assert.ok(await page.locator('.crew-group[aria-hidden=true] a').evaluateAll(es=>es.every(e=>e.tabIndex===-1)));
assert.equal(await page.locator('#crew').getByRole('link').count(),70); // RSI org + 69 unique profiles
await page.clock.runFor(100);
let start=await left();
await page.clock.runFor(2000);
assert.ok((await left())-start>35&&(await left())-start<50,JSON.stringify({start,end:await left(),width,running:await rail.getAttribute('data-running'),looping:await rail.getAttribute('data-looping')}));
checks.push('22px/s movement; 69 accessible member links, visual copies excluded from tab order and accessibility tree');
await page.locator('.crew-toolbar').hover();
start=await left();await page.clock.runFor(2000);assert.equal(await left(),start);
await page.mouse.move(0,0);await page.clock.runFor(1000);assert.ok(await left()>start);
const first=page.locator('[data-copy=original] .crew-card').first();
await first.focus();start=await left();await page.clock.runFor(2000);assert.equal(await left(),start);
await first.evaluate(e=>e.blur());await page.mouse.move(0,0);
checks.push('Hover/focus pause and resume');
await page.getByRole('button',{name:'Pause crew scrolling',exact:true}).click();
await page.evaluate(()=>document.activeElement.blur());await page.mouse.move(0,0);
start=await left();await page.clock.runFor(3000);assert.equal(await left(),start);
await page.getByRole('button',{name:'Play crew scrolling',exact:true}).click();
await page.evaluate(()=>document.activeElement.blur());await page.mouse.move(0,0);
await page.clock.runFor(1000);assert.ok(await left()>start);
checks.push('Explicit pause/play control persists independently of temporary pauses');
await rail.evaluate((e,w)=>e.scrollLeft=2*w-8,width);
await page.clock.runFor(1000);
assert.ok(await left()>width&&await left()<width+40,JSON.stringify({test:'seam',width,left:await left(),running:await rail.getAttribute('data-running')}));
checks.push('Forward seam wraps into identical content without resetting to the first pixel');
await rail.hover();
await page.mouse.wheel(180,0);
await page.mouse.move(0,0);
await page.clock.runFor(1000);
assert.equal(await rail.getAttribute('data-running'),'false');
await page.clock.runFor(3000);
assert.equal(await rail.getAttribute('data-running'),'true');
checks.push('Manual wheel input pauses motion and resumes after idle delay');
await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))});
start=await left();await page.clock.runFor(2000);assert.equal(await left(),start);
await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'))});
checks.push('Hidden-document visibility pauses animation');
await page.locator('#home').scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('.crew-rail').dataset.running==='false');
start=await left();await page.clock.runFor(2000);assert.equal(await left(),start);
checks.push('No animation while offscreen');
await page.locator('#crew').scrollIntoViewIfNeeded();
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>document.querySelectorAll('.crew-group').length===1);
start=await left();await page.clock.runFor(3000);assert.equal(await left(),start);
assert.equal(await page.getByRole('button',{name:'Pause crew scrolling',exact:true}).count(),0);
checks.push('Live reduced-motion change stops movement and removes duplicate groups');
await page.close();
const mobile=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'no-preference'});
await mobile.route(/https:\/\/[^/]*robertsspaceindustries\.com\//,r=>r.fulfill({contentType:'image/png',body:avatar}));
await mobile.clock.install({time:new Date('2026-10-09T15:00:00Z')});
await mobile.clock.pauseAt(new Date('2026-10-09T15:00:01Z'));
await mobile.goto('http://localhost:5174/',{waitUntil:'networkidle'});
await mobile.locator('#crew').scrollIntoViewIfNeeded();
await mobile.waitForFunction(()=>document.querySelector('.crew-rail').dataset.running==='true');
await mobile.clock.runFor(100);
let mobileStart=await mobile.locator('.crew-rail').evaluate(e=>e.scrollLeft);
await mobile.clock.runFor(1500);
assert.ok(await mobile.locator('.crew-rail').evaluate(e=>e.scrollLeft)>mobileStart);
const box=await mobile.locator('.crew-rail').boundingBox();
const cdp=await mobile.context().newCDPSession(mobile);
const x=box.x+250,y=box.y+65;
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
for(let d=20;d<=120;d+=20)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-d,y}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
assert.equal(await mobile.locator('.crew-rail').getAttribute('data-running'),'false');
await mobile.clock.runFor(5000);
assert.equal(await mobile.locator('.crew-rail').getAttribute('data-running'),'true');
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await mobile.screenshot({path:'previews/crew-autoscroll-mobile.png',fullPage:true});
await mobile.close();
checks.push('Mobile automatic motion and native swipe pause/resume without sticky synthetic hover');
for(const count of [0,1]){
 const single=await browser.newPage({reducedMotion:'no-preference'});
 const roster=JSON.parse(await readFile('public/data/members.json','utf8'));roster.members=roster.members.slice(0,count);
 await single.route('**/data/members.json',r=>r.fulfill({json:roster}));
 await single.goto('http://localhost:5174/',{waitUntil:'networkidle'});
 assert.equal(await single.locator('.crew-group').count(),1);
 assert.equal(await single.locator('.crew-rail').getAttribute('data-running'),'false');
 await single.close();
}
checks.push('Empty and single-member rosters do not loop');
assert.deepEqual(errors,[]);
await writeFile('previews/crew-motion-results.json',JSON.stringify({checks,pageErrors:errors},null,2));
console.log(JSON.stringify({checks,pageErrors:errors},null,2));
await browser.close();
